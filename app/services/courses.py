"""Генерация обучающих микро-курсов через YandexGPT (перенос из прошлой версии).

Курс = шаги двух типов: content (текст урока) и quiz (вопрос с вариантами).
Материалом может быть тема, произвольный текст или слабые стороны из разборов
диалогов — так обучение строится на реальных ошибках сотрудника.
"""

from app.services import llm

_COURSE_PROMPT = """
Ты — опытный методолог и бизнес-тренер розничных продаж. Создай структуру
микро-курса для мобильного обучения линейного сотрудника.

Верни ответ СТРОГО в валидном JSON без пояснений:
{
  "title": "Цепляющее название курса",
  "description": "Краткое описание пользы (до 150 символов)",
  "category": "Sales" или "Service" или "Psychology" или "Menu",
  "steps": [
    {"id": "s1", "type": "content", "title": "Заголовок урока",
     "content": "Текст обучения (2-3 абзаца)"},
    {"id": "s2", "type": "quiz", "title": "Проверка знаний",
     "question": {"text": "Вопрос", "options": ["Вариант А", "Вариант Б", "Вариант В"],
                  "correctOption": 0}}
  ]
}
Сделай минимум 4 шага, чередуя content и quiz. Пиши по-русски, конкретно и практично.
"""


async def generate_course(topic: str, material: str = "") -> dict:
    """Сгенерировать структуру курса по теме и (опционально) материалу."""
    user_text = f"Тема курса: {topic}."
    if material.strip():
        user_text += (
            f"\nИспользуй следующий материал (реальные ошибки/контекст):\n{material[:4000]}"
        )
    return await llm.complete_json(_COURSE_PROMPT, user_text, temperature=0.5, max_tokens=6000)
