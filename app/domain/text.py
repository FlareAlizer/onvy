"""Работа с русским текстом на слух.

Всё, что здесь есть, существует по одной причине: распознавание речи в шумном
зале выдаёт не то, что человек сказал. Падежи, проглоченные окончания, «Азиз»
вместо «Азиза» и наоборот. Сравнивать такие слова напрямую бессмысленно.

Это не морфология и не претендует ею быть — грубые правила, которых хватает,
чтобы узнать блюдо в меню и имя коллеги на смене.
"""

import re

# Окончания, которые официант меняет на лету: «шурпы», «лагмана», «бараниной»,
# «кухне», «Азизу». Длинные проверяются первыми.
_ENDINGS = (
    "ами", "ями", "ого", "ему", "ому", "ыми", "ими",
    "ой", "ей", "ом", "ем", "ам", "ям", "ах", "ях", "ов", "ев", "ый", "ий", "ая",
    "яя", "ое", "ее", "ые", "ие", "ью",
    "а", "я", "ы", "и", "у", "ю", "е", "о", "й", "ь",
)

# Короче этого основу не режем: «чай», «рис», «лук», «бар» должны остаться собой.
MIN_STEM = 3


def normalize(text: str) -> str:
    """Нижний регистр без ё — ниже по цепочке все сравнения идут в этом виде."""
    return text.lower().replace("ё", "е")


def words(text: str | None) -> list[str]:
    """Слова текста по порядку, нормализованные."""
    if not text:
        return []
    return re.findall(r"\w+", normalize(text))


def stem(word: str) -> str:
    """Отрезать падежное окончание, если после него остаётся осмысленная основа."""
    for ending in _ENDINGS:
        if word.endswith(ending) and len(word) - len(ending) >= MIN_STEM:
            return word[: -len(ending)]
    return word


def _distance_within(first: str, second: str, limit: int) -> bool:
    """Отличаются ли слова не больше чем на limit правок.

    Обычное расстояние Левенштейна, но с ранним выходом: нам не нужна точная
    величина, только ответ «достаточно ли похоже».
    """
    if abs(len(first) - len(second)) > limit:
        return False
    previous = list(range(len(second) + 1))
    for i, a in enumerate(first, start=1):
        current = [i]
        for j, b in enumerate(second, start=1):
            current.append(
                min(
                    previous[j] + 1,
                    current[j - 1] + 1,
                    previous[j - 1] + (a != b),
                )
            )
        if min(current) > limit:
            return False
        previous = current
    return previous[-1] <= limit


# Звуки, которые распознавание путает между собой в шумном зале. Безударные
# гласные сливаются («лОнгман» вместо «лАгман»), парные согласные глохнут
# («сОмса» вместо «сАмса», «манТу» вместо «манТы»), шипящие смешиваются.
#
# Ключ — что могло приехать, значение — к чему приводим. Обе стороны сравнения
# сворачиваются одинаково, поэтому направление свёртки роли не играет: важно
# только, что «о» и «а» после неё неразличимы.
_ЗВУКИ = str.maketrans(
    {
        "о": "а", "э": "е", "и": "е", "ы": "е", "я": "а", "ю": "у",
        "б": "п", "д": "т", "г": "к", "в": "ф", "ж": "ш", "з": "с",
        "щ": "ш", "ц": "с",
        "ъ": "", "ь": "",
    }
)


def _звуковой(word: str) -> str:
    """Слово, свёрнутое до различимых на слух звуков.

    Сдвоенные буквы схлопываем: «панна-котта» и «панакота» на слух одно и то же,
    а для расстояния Левенштейна — два лишних расхождения.
    """
    свёрнутое = word.translate(_ЗВУКИ)
    out: list[str] = []
    for буква in свёрнутое:
        if not out or out[-1] != буква:
            out.append(буква)
    return "".join(out)


def _допуск(length: int, loose: bool) -> int:
    """Сколько правок прощаем слову такой длины.

    Короткие слова не прощают ничего: «рис» и «рас» — разные вещи. Длинным в
    вольном режиме прощаем две: распознавание ошибается в них чаще, а спутать
    два разных длинных названия блюда двумя правками почти невозможно.
    """
    if loose and length >= 8:
        return 2
    if length >= 5:
        return 1
    return 0


def sounds_like(spoken: str, target: str, *, loose: bool = False) -> bool:
    """Похоже ли услышанное слово на искомое.

    Порядок от точного к вольному, чтобы дешёвое совпадение не уступало место
    догадке: точное слово, совпадение основ (это падежи), затем правки в
    буквенной записи и, наконец, в звуковой.

    `loose` включается только для поиска по меню. Цена ошибки здесь разная и
    несимметричная: не узнать блюдо — официант зря переспросит, не узнать
    коллегу — личное сообщение уедет чужому человеку. Поэтому адресация
    коллег и отделов остаётся строгой, а меню ищется вольно.

    Звуковая ступень добавлена по живому пилоту: «что в составе лонгмана» не
    находило лагман, потому что «лонгман» и «лагман» отличаются на две правки
    (о→а и лишняя «н»). После свёртки в звуки расхождение остаётся одно, и блюдо
    находится — а официант получает состав вместо «такого в меню не нашёл».
    """
    if spoken == target:
        return True

    spoken_stem, target_stem = stem(spoken), stem(target)
    if spoken_stem == target_stem:
        return True

    предел = _допуск(min(len(spoken_stem), len(target_stem)), loose)
    if предел and _distance_within(spoken_stem, target_stem, предел):
        return True

    if not loose:
        return False

    звук_с, звук_ц = _звуковой(spoken_stem), _звуковой(target_stem)
    if звук_с == звук_ц:
        return True
    предел_звука = _допуск(min(len(звук_с), len(звук_ц)), loose)
    return bool(предел_звука) and _distance_within(звук_с, звук_ц, предел_звука)
