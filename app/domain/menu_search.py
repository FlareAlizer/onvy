"""Подбор блюд под вопрос официанта.

Ассистент отвечает только по карточкам, которые сюда попали. Значит качество
ответа определяется этим модулем, а не моделью: не нашли блюдо — ответа не будет,
нашли лишнее — модель начнёт путаться между похожими позициями.

Логика намеренно простая и объяснимая. В шумном зале важнее предсказуемость,
чем хитрость: если официант скажет «лагман», он должен получить лагман, а не
«похожее по эмбеддингу». Эмбеддинги — следующий шаг, когда меню перестанет
помещаться в контекст.
"""

from app.domain.dish_aliases import известна, канон
from app.domain.text import sounds_like, stem
from app.domain.text import words as text_words
from app.ports.menu import MenuItemData

# Слова, которые есть в любом вопросе и ничего не говорят о блюде.
_STOPWORDS = frozenset(
    {
        "а", "в", "во", "на", "и", "или", "ли", "есть", "у", "нас", "мне", "мы",
        "это", "что", "как", "сколько", "стоит", "цена", "по", "за", "с", "к",
        "нужен", "нужна", "нужно", "хочу", "дай", "покажи", "где", "какой",
        "какая", "какие", "там", "ещё", "еще", "бы", "же", "ну", "вот",
        "составе", "состав", "входит", "блюде", "блюдо", "порция", "грамм",
        "the", "a", "is", "do", "we", "have", "in", "of",
    }
)

# Вес совпадения: попадание в название решает, состав — лишь подсказка.
_WEIGHT_NAME = 4
_WEIGHT_CATEGORY = 2
_WEIGHT_COMPOSITION = 1


def tokenize(text: str) -> set[str]:
    """Значимые слова запроса — без служебных и слишком коротких.

    Соседние слова дополнительно склеиваются, если склейка есть в таблице
    синонимов: «ачик чучук», «том ям», «люля кебаб» официант произносит
    раздельно, а в меню они записаны одним словом. Склеиваем только известное —
    иначе из любой пары слов рождалось бы несуществующее блюдо.
    """
    все = text_words(text)
    значимые = {w for w in все if len(w) > 2 and w not in _STOPWORDS}
    for первое, второе in zip(все, все[1:], strict=False):
        склейка = первое + второе
        if известна(stem(склейка)):
            значимые.add(склейка)
    return значимые


def _words(text: str | None) -> set[str]:
    return {w for w in text_words(text) if len(w) > 2}




def _похоже(token: str, слово: str) -> bool:
    """Одно ли это слово для поиска по меню.

    Сначала синонимы: «том ям», «томьям» и «тон ям» — одно блюдо, и формулой это
    не выводится, тут нужен словарь (app/domain/dish_aliases.py). Затем вольное
    сравнение на слух: оно вытягивает то, чего в словаре нет и быть не может —
    названия из меню, загруженного этим заведением сегодня утром.
    """
    if канон(stem(token)) == канон(stem(слово)):
        return True
    return sounds_like(token, слово, loose=True)


def score(query_tokens: set[str], item: MenuItemData) -> int:
    """Насколько позиция подходит под вопрос."""
    name_words = _words(item.name)
    category_words = _words(item.category)
    composition_words = _words(item.composition)

    total = 0
    for token in query_tokens:
        if any(_похоже(token, w) for w in name_words):
            total += _WEIGHT_NAME
        elif any(_похоже(token, w) for w in category_words):
            total += _WEIGHT_CATEGORY
        elif any(_похоже(token, w) for w in composition_words):
            total += _WEIGHT_COMPOSITION
    return total


# Вопросы, где блюдо не названо вовсе, а выбрать его должен ассистент:
# «что посоветовать», «что быстрее приготовят», «какое самое острое».
# Список намеренно узкий — только советующие и сравнительные слова. Общие «что»
# и «есть» сюда брать нельзя: «есть ли суши» — это вопрос про конкретное блюдо,
# которого у нас нет, и ответом обязано быть честное «такого в меню не нашёл»,
# а не пересказ половины меню.
_ОБЗОРНЫЕ_СЛОВА = frozenset(
    {
        "посоветовать", "посоветуй", "посоветуешь", "предложить", "предложи",
        "выбрать", "лучше", "быстрее", "дешевле", "подешевле", "дороже",
        "легче", "острее", "самый", "самое", "самая", "самые",
        "вегетарианец", "вегетарианцу", "вегетарианка", "постное", "постный",
        "детское", "детям", "порекомендуй", "рекомендуешь",
    }
)

# Слова, которыми спрашивают про постное и вегетарианское.
_ВЕГЕТАРИАНСКИЙ_ВОПРОС = frozenset(
    {"вегетарианец", "вегетарианцу", "вегетарианка", "вегетарианский", "постное", "постный"}
)

# Корни мясного и рыбного в составе. Список держим коротким и однозначным:
# он не решает за кухню, а лишь убирает из выборки заведомо неподходящее.
_МЯСНЫЕ_КОРНИ = (
    "мясо", "мясн", "барани", "говяд", "свин", "курин", "куриц", "куриц", "телят",
    "конск", "казы", "фарш", "колбас", "язык", "рыб", "лосос", "креветк", "морепродукт",
)


def _вегетарианское(item: MenuItemData) -> bool:
    """Нет ли в составе заведомо мясного или рыбного.

    Незаполненный состав вегетарианским не считаем: «не знаем» — это не «можно».
    """
    if not item.composition:
        return False
    состав = item.composition.casefold()
    return not any(корень in состав for корень in _МЯСНЫЕ_КОРНИ)


# Сколько карточек отдаём, когда блюдо не названо. Обзорный вопрос требует выбора
# из многого, но весь список слать нельзя: он раздувает запрос и замедляет ответ,
# который официант ждёт стоя перед гостем.
_ОБЗОРНЫЙ_ПРЕДЕЛ = 25


def search(question: str, items: list[MenuItemData], limit: int = 5) -> list[MenuItemData]:
    """Подобрать позиции меню под вопрос, по убыванию релевантности.

    Пустой результат — валидный ответ, когда спросили про блюдо, которого нет:
    ассистент честно скажет «не нашёл такого в меню».

    Но есть вопросы, где блюдо не названо и не должно быть: «что посоветовать
    вегетарианцу», «что готовится быстрее». По словам такого вопроса не совпадёт
    ни одна карточка, и ассистент отвечал «не нашёл» — на вопрос, ответ на
    который лежит прямо в меню. Поэтому на обзорный вопрос отдаём срез меню и
    даём модели выбрать: выбор по карточкам — это не выдумывание, а работа.
    """
    tokens = tokenize(question)
    if not tokens:
        return []

    scored = [(item, score(tokens, item)) for item in items]
    relevant = [(item, value) for item, value in scored if value > 0]
    relevant.sort(key=lambda pair: (-pair[1], pair[0].name))
    if relevant:
        return [item for item, _ in relevant[:limit]]

    if any(token in _ОБЗОРНЫЕ_СЛОВА for token in tokens):
        # Спросили про постное — мясное отсеиваем здесь, а не надеемся, что
        # модель прочитает состав каждой карточки. Проверено на живом меню:
        # получив два десятка карточек, она уверенно советовала вегетарианцу
        # долму с бараниной и лагман с говядиной.
        if any(token in _ВЕГЕТАРИАНСКИЙ_ВОПРОС for token in tokens):
            подходящие = [item for item in items if _вегетарианское(item)]
            return подходящие[:_ОБЗОРНЫЙ_ПРЕДЕЛ]
        return items[:_ОБЗОРНЫЙ_ПРЕДЕЛ]
    return []
