def _построить() -> dict[str, str]:
    """Основа слова → канон группы.

    Ключом берём именно основу: официант говорит «лагмана», «манты», «с
    цезарем», и сравнивать нужно то же, что сравнивает поиск по меню.
    """
    таблица: dict[str, str] = {}
    for группа in _ГРУППЫ:
        канон = stem(группа[0])
        for слово in группа:
            таблица.setdefault(stem(слово), канон)
    return таблица


_ПО_ОСНОВЕ = _построить()


def известна(основа: str) -> bool:
    """Есть ли такое написание в таблице.

    Нужно поиску, чтобы решить, склеивать ли соседние слова: «ачик чучук» и
    «том ям» произносятся раздельно, а в меню записаны одним словом или иначе
    разбиты. Склеивать всё подряд нельзя — так из «салат ромэн» получится
    несуществующее блюдо, — поэтому склейка разрешена только для известных нам.
    """
    return основа in _ПО_ОСНОВЕ


def канон(основа: str) -> str:
    """Каноническая форма основы, если слово известно, иначе она сама.

    Незнакомое слово возвращается как есть — таблица только помогает, но никогда
    не мешает: меню заведения мы в лицо не знаем и подменять его словарём нельзя.
    """
    return _ПО_ОСНОВЕ.get(основа, основа)


def синонимы(слово: str) -> frozenset[str]:
    """Все известные написания слова — для диагностики и тестов."""
    цель = канон(stem(слово))
    return frozenset(
        вариант for вариант, к in _ПО_ОСНОВЕ.items() if к == цель
    ) or frozenset({stem(слово)})
