"""Подбор блюд под вопрос официанта — на меню настоящей чайханы."""

from decimal import Decimal

import pytest

from app.domain.menu_search import search, tokenize
from app.ports.menu import MenuItemData


def блюдо(
    external_id: str,
    name: str,
    category: str | None = None,
    composition: str | None = None,
) -> MenuItemData:
    return MenuItemData(
        external_id=external_id,
        name=name,
        category=category,
        price=Decimal("450"),
        composition=composition,
    )


МЕНЮ = [
    блюдо("lagman", "Лагман", "Горячее", "лапша, говядина, перец болгарский"),
    блюдо("plov", "Плов по-фергански", "Горячее", "рис девзира, баранина, морковь"),
    блюдо("samsa", "Самса с бараниной", "Выпечка", "слоёное тесто, баранина, лук"),
    блюдо("shurpa", "Шурпа", "Супы", "баранина, картофель, помидоры"),
    блюдо("tea", "Чай зелёный", "Напитки", "чайный лист"),
    блюдо("salad", "Салат Ачичук", "Салаты", "помидоры, лук, острый перец"),
]


def test_прямое_название_находится():
    результат = search("что в составе лагмана", МЕНЮ)

    assert результат[0].external_id == "lagman"


def test_падеж_не_ломает_поиск():
    """Официант говорит «шурпы», в меню «Шурпа»."""
    результат = search("сколько стоит шурпы", МЕНЮ)

    assert результат[0].external_id == "shurpa"


def test_поиск_по_составу_работает_но_слабее_названия():
    """«Баранина» есть в трёх блюдах — все найдутся, но название важнее."""
    результат = search("что есть с бараниной", МЕНЮ)
    идентификаторы = [позиция.external_id for позиция in результат]

    assert "samsa" in идентификаторы
    assert "shurpa" in идентификаторы
    # Самса с бараниной в названии — она должна быть выше шурпы.
    assert идентификаторы.index("samsa") < идентификаторы.index("shurpa")


def test_поиск_по_категории():
    результат = search("какие есть напитки", МЕНЮ)

    assert [позиция.external_id for позиция in результат] == ["tea"]


def test_ничего_не_нашлось_это_валидный_ответ():
    """Лучше пусто, чем случайные блюда: ассистент честно скажет «нет такого»."""
    результат = search("есть ли суши", МЕНЮ)

    assert результат == []


def test_вопрос_из_одних_служебных_слов_ничего_не_возвращает():
    assert search("а что у нас есть", МЕНЮ) == []


def test_лимит_соблюдается():
    результат = search("баранина помидоры лапша чай рис", МЕНЮ, limit=2)

    assert len(результат) == 2


def test_короткие_слова_не_засоряют_запрос():
    assert "по" not in tokenize("что по плову")
    assert "плову" in tokenize("что по плову")


class TestОбзорныйВопрос:
    """Вопросы, где блюдо не названо и не должно быть.

    «Что посоветовать вегетарианцу», «что готовится быстрее» — по словам такого
    вопроса не совпадёт ни одна карточка, и ассистент отвечал «не нашёл такого в
    меню» на вопрос, ответ на который лежит прямо в меню. Выбор по карточкам —
    это работа ассистента, а не выдумывание.
    """

    @pytest.mark.parametrize(
        "вопрос",
        [
            "что посоветовать вегетарианцу",
            "что готовится быстрее всего",
            "какое блюдо самое острое",
            "что можно взять подешевле",
        ],
    )
    def test_обзорный_вопрос_получает_срез_меню(self, вопрос):
        найдено = search(вопрос, МЕНЮ)

        assert найдено, f"«{вопрос}» не получил ни одной карточки"

    def test_спросили_про_несуществующее_блюдо_и_получили_пусто(self):
        """Обратная сторона: выдуманное блюдо не должно тянуть за собой всё меню,
        иначе ассистент начнёт рассказывать про что угодно вместо честного «нет»."""
        найдено = search("суши с лососем", МЕНЮ)

        assert найдено == []


class TestПостноеОтсеиваетсяДоМодели:
    """Мясное убираем из выборки сами.

    Проверено на живом меню: получив два десятка карточек, модель уверенно
    советовала вегетарианцу долму с бараниной и лагман с говядиной. Читать состав
    каждой карточки — работа кода, а не надежда на внимательность модели.
    """

    def test_мясное_не_попадает_в_выборку(self):
        найдено = search("что посоветовать вегетарианцу", МЕНЮ)

        for позиция in найдено:
            состав = (позиция.composition or "").casefold()
            assert "барани" not in состав, f"«{позиция.name}» с бараниной для вегетарианца"
            assert "говяд" not in состав, f"«{позиция.name}» с говядиной для вегетарианца"

    def test_незаполненный_состав_вегетарианским_не_считается(self):
        """«Не знаем состав» — это не «можно»: гостю такое советовать нельзя."""
        меню = [
            MenuItemData(
                external_id="x",
                name="Загадка",
                category="Горячее",
                price=Decimal("100"),
                composition=None,
            )
        ]

        assert search("что посоветовать вегетарианцу", меню) == []
